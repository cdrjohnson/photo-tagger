// Downloads a handful of public-domain / CC0 sample photos from Wikimedia Commons
// (1024px thumbnails), writes samples/ATTRIBUTION.md, and derives a few test variants
// (blurred, dark, geotagged) with sharp. Run: npm run samples
import fs from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const OUT = path.resolve('samples')
const UA = { 'User-Agent': 'photo-tagger-sample-fetch/1.0 (https://github.com/cdrjohnson; demo samples)' }
const PICKS = [
  ['dog.jpg', 'File:Golden-retriever-dog-1362597631o6g.jpg'],
  ['cat.jpg', 'File:Domestic shorthair cat portrait in grass.jpg'],
  ['beach.jpg', 'File:Sunset, Lone Ranch Beach, Oregon.jpg'],
  ['city.jpg', 'File:New York City skyline from ferry.jpg'],
  ['pizza.jpg', 'File:Pizza with mushrooms and cheese.jpg'],
  ['mountain.jpg', 'File:Mountain landscape near Los Silos, Tenerife, Canary Islands, Spain 01.jpg'],
  ['person.jpg', 'File:Kalpana Chawla, NASA photo portrait in orange suit.jpg'],
  ['document.jpg', 'File:W.E.F. Britten - The Early Poems of Alfred, Lord Tennyson - The Deserted House.jpg'],
  // Face-recognition test set: four public-domain US government photos of the same person (Joe Biden),
  // one of them a two-person photo, plus a different person (Barack Obama) as a distractor
  ['biden-2013.jpg', 'File:Joe Biden official portrait 2013.jpg'],
  ['biden-2021.jpg', 'File:Joe Biden presidential portrait.jpg'],
  ['biden-2009.jpg', 'File:FEMA - 41717 - Vice President Joe Biden - Official Portrait.jpg'],
  ['obama-biden-2009.jpg', 'File:Official portrait of President Obama and Vice President Biden 2009.jpg'],
  ['obama-portrait.jpg', 'File:President Barack Obama.jpg'],
]
const strip = (s) => (s || '').replace(/<[^>]+>/g, '').trim()

await fs.mkdir(OUT, { recursive: true })
const lines = [
  '# Sample image attribution',
  '',
  'Sample photos used by the end-to-end tests and screenshots. All were downloaded from Wikimedia Commons (1024 px wide thumbnails) and are CC0 or public domain. The five White House / FEMA photos (biden-*, obama-*) are works of the US federal government (public domain in the US) and are used to test face recognition: the same person (Joe Biden) in four photos – one of them together with Barack Obama – plus a portrait of Barack Obama as a distractor. person.jpg (Kalpana Chawla, NASA) is a second distractor.',
  '',
  '| File | Commons page | Licence | Author |',
  '|---|---|---|---|',
]
for (const [name, title] of PICKS) {
  const api = 'https://commons.wikimedia.org/w/api.php?' + new URLSearchParams({
    action: 'query', titles: title, prop: 'imageinfo', iiprop: 'url|extmetadata', iiurlwidth: '1024', format: 'json',
  })
  const j = await (await fetch(api, { headers: UA })).json()
  const page = Object.values(j.query.pages)[0]
  const ii = page.imageinfo[0]
  const buf = Buffer.from(await (await fetch(ii.thumburl, { headers: UA })).arrayBuffer())
  await fs.writeFile(path.join(OUT, name), buf)
  const m = ii.extmetadata
  lines.push(`| ${name} | [${title.replace('File:', '')}](${ii.descriptionurl}) | ${strip(m.LicenseShortName?.value)} | ${strip(m.Artist?.value).replace(/\|/g, '/').slice(0, 80)} |`)
  console.log('downloaded', name, buf.length)
}

// Derived variants (made locally from the downloaded files)
await sharp(path.join(OUT, 'mountain.jpg')).blur(14).jpeg({ quality: 85 }).toFile(path.join(OUT, 'blurry-mountain.jpg'))
await sharp(path.join(OUT, 'city.jpg')).modulate({ brightness: 0.12 }).jpeg({ quality: 85 }).toFile(path.join(OUT, 'dark-city.jpg'))
await sharp(path.join(OUT, 'beach.jpg'))
  .modulate({ brightness: 1.1 }).linear(1.0, 140).jpeg({ quality: 85 }).toFile(path.join(OUT, 'bright-beach.jpg'))
await sharp(path.join(OUT, 'cat.jpg'))
  .withExif({
    IFD0: { Make: 'SampleCam', Model: 'Sample Phone 1', DateTime: '2021:07:04 10:30:00' },
    IFD2: { DateTimeOriginal: '2021:07:04 10:30:00' },
    IFD3: { GPSLatitudeRef: 'N', GPSLatitude: '48/1 51/1 30/1', GPSLongitudeRef: 'E', GPSLongitude: '2/1 17/1 40/1' },
  })
  .jpeg({ quality: 85 }).toFile(path.join(OUT, 'geotagged-cat.jpg'))
lines.push('', 'Derived locally with sharp (not separate photos): `blurry-mountain.jpg` (Gaussian blur of mountain.jpg), `dark-city.jpg` (city.jpg darkened), `bright-beach.jpg` (beach.jpg brightened), `geotagged-cat.jpg` (cat.jpg with synthetic EXIF: camera "SampleCam Sample Phone 1", 4 Jul 2021, GPS 48.8583 N, 2.2944 E). `screenshot.png` is generated by the test scripts from a local HTML page.', '')
await fs.writeFile(path.join(OUT, 'ATTRIBUTION.md'), lines.join('\n'))
